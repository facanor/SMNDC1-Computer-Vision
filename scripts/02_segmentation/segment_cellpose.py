#!/usr/bin/env python3
"""Cellpose segmentation and segmentation QC for SMNDC1 TMA sections.

The script expects pre-separated fluorescence channels under each Exon4 and
NoExon4 root directory:

    CHAN_B_nucleosIF/       nuclear channel
    CHAN_G_proteinaIF/      SMNDC1/protein channel
    CHAN_R_citoplasmaIF/    cytoplasmic / pan-cytokeratin channel

Segmentation outputs are written next to the corresponding channel images:

    *_B_nucleos8_nuc_masks.tif    nuclear instance labels
    *_R_citoplasma8_cp_masks.tif  cell/cytoplasmic instance labels
    *_G_proteina8_prot_mask.tif   binary protein-positive mask

Two subcommands are provided:

    segment   run Cellpose segmentation and protein-mask generation
    qc        summarize cells, nuclei, and nuclei-per-cell counts

The legacy subcommand names ``segment_s`` and ``qc_s`` are accepted as aliases.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
from pathlib import Path

import numpy as np
import pandas as pd
from skimage import filters, morphology
from skimage.util import img_as_float32
from tifffile import imread, imwrite
from tqdm import tqdm


CHANNEL_DIRS = {
    "B": "CHAN_B_nucleosIF",
    "G": "CHAN_G_proteinaIF",
    "R": "CHAN_R_citoplasmaIF",
}

MASK_SUFFIXES = ("_cp_masks.tif", "_nuc_masks.tif", "_prot_mask.tif")


def core_norm_from_fname(filename: str) -> str:
    """Return a normalized core identifier from a channel or mask filename."""
    basename = os.path.basename(filename)
    match = re.search(r"^(.+?)\.ome", basename, flags=re.IGNORECASE)
    if match:
        core = match.group(1)
    else:
        core = os.path.splitext(basename)[0]
        core = re.sub(
            r"_(?:B_nucleos8|G_proteina8|R_citoplasma8)(?:_(?:nuc|cp|prot)_masks?)?$",
            "",
            core,
            flags=re.IGNORECASE,
        )
    return core.replace("-", "_")


def list_channel_images(channel_dir: str) -> list[str]:
    """List channel TIFFs while excluding masks generated by this pipeline."""
    paths: list[str] = []
    for filename in os.listdir(channel_dir):
        lower = filename.lower()
        if not lower.endswith((".tif", ".tiff")):
            continue
        if any(lower.endswith(suffix) for suffix in MASK_SUFFIXES):
            continue
        paths.append(os.path.join(channel_dir, filename))
    return sorted(paths)


def make_out_path(image_path: str, suffix: str) -> str:
    """Append a segmentation suffix to a TIFF filename."""
    lower = image_path.lower()
    if lower.endswith(".tiff"):
        return image_path[:-5] + suffix
    if lower.endswith(".tif"):
        return image_path[:-4] + suffix
    raise ValueError(f"Expected a TIFF image, got: {image_path}")


def read_2d(path: str) -> np.ndarray:
    """Read a single-channel TIFF and require a two-dimensional image."""
    image = np.asarray(imread(path))
    image = np.squeeze(image)
    if image.ndim != 2:
        raise ValueError(
            f"Expected a 2D single-channel image after squeezing singleton axes; "
            f"got shape {image.shape} for {path}"
        )
    return image


def protein_mask_from_image(
    protein_image: np.ndarray,
    tumor_region: np.ndarray | None = None,
    min_size: int = 16,
    close_radius: int = 1,
) -> np.ndarray:
    """Create a binary protein-positive mask using an Otsu threshold."""
    protein_float = img_as_float32(protein_image)

    if tumor_region is not None and int(np.count_nonzero(tumor_region)) > 50:
        values = protein_float[np.asarray(tumor_region, dtype=bool)]
    else:
        values = protein_float.ravel()

    values = values[np.isfinite(values)]
    if values.size == 0:
        raise ValueError("Protein channel contains no finite pixels.")

    if float(np.nanstd(values)) < 1e-6:
        threshold = float(np.nanmean(values) + 1e-6)
    else:
        threshold = float(filters.threshold_otsu(values))

    mask = protein_float > threshold

    if close_radius > 0:
        mask = morphology.binary_closing(mask, morphology.disk(int(close_radius)))
    if min_size > 0:
        mask = morphology.remove_small_objects(mask, min_size=int(min_size))

    return mask.astype(np.uint8)


def require_cellpose():
    """Import Cellpose only when segmentation is requested."""
    try:
        from cellpose import models
    except Exception as exc:  # pragma: no cover - depends on local environment
        raise RuntimeError(
            "Cellpose could not be imported. Install the analysis environment "
            "and verify that Cellpose is available (manuscript environment: "
            "Cellpose 3.1.1.2)."
        ) from exc
    return models


def evaluate_cellpose(
    model,
    image: np.ndarray,
    channels: list[int],
    diameter: float,
    flow_threshold: float,
    cellprob_threshold: float,
) -> np.ndarray:
    """Run a Cellpose model and return integer instance labels."""
    masks, _flows, _styles, _diameters = model.eval(
        image,
        channels=channels,
        diameter=diameter if diameter > 0 else None,
        flow_threshold=flow_threshold,
        cellprob_threshold=cellprob_threshold,
    )
    masks = np.asarray(masks)
    if masks.ndim != 2:
        raise ValueError(f"Cellpose returned a non-2D mask with shape {masks.shape}.")
    if masks.max(initial=0) <= np.iinfo(np.uint16).max:
        return masks.astype(np.uint16, copy=False)
    return masks.astype(np.uint32, copy=False)


def channel_maps(root: str) -> tuple[dict[str, str], dict[str, str], dict[str, str]]:
    """Build core-to-image maps for B, G, and R channels under one dataset root."""
    dirs = {key: os.path.join(root, dirname) for key, dirname in CHANNEL_DIRS.items()}
    for key, directory in dirs.items():
        if not os.path.isdir(directory):
            raise FileNotFoundError(f"Expected channel directory for {key}: {directory}")

    b_map = {core_norm_from_fname(path): path for path in list_channel_images(dirs["B"])}
    g_map = {core_norm_from_fname(path): path for path in list_channel_images(dirs["G"])}
    r_map = {core_norm_from_fname(path): path for path in list_channel_images(dirs["R"])}
    return b_map, g_map, r_map


def cmd_segment(args: argparse.Namespace) -> None:
    """Run nuclear/cytoplasmic Cellpose segmentation for Exon4 and NoExon4 roots."""
    groups = [("S_exon", args.s_exon_root), ("S_noexon", args.s_noex_root)]
    output_rows: list[dict[str, object]] = []

    models = None
    nuclear_model = None
    cytoplasm_model = None

    for group_name, root in groups:
        b_map, g_map, r_map = channel_maps(root)
        common = sorted(set(b_map) & set(g_map) & set(r_map))
        if args.max_cores > 0:
            common = common[: args.max_cores]

        print(f"[{group_name}] cores with B/G/R channels: {len(common)}")

        for core in tqdm(common, desc=f"segment {group_name}", ncols=90):
            b_path, g_path, r_path = b_map[core], g_map[core], r_map[core]
            out_nuc = make_out_path(b_path, "_nuc_masks.tif")
            out_cyto = make_out_path(r_path, "_cp_masks.tif")
            out_prot = make_out_path(g_path, "_prot_mask.tif")

            need_nuc = args.overwrite or not os.path.exists(out_nuc)
            need_cyto = args.overwrite or not os.path.exists(out_cyto)
            need_prot = args.overwrite or not os.path.exists(out_prot)

            if not (need_nuc or need_cyto or need_prot):
                output_rows.append(
                    {
                        "group": group_name,
                        "core": core,
                        "B_img": b_path,
                        "R_img": r_path,
                        "G_img": g_path,
                        "B_nuc_mask": out_nuc,
                        "R_cyto_mask": out_cyto,
                        "G_prot_mask": out_prot,
                        "status": "skipped_exists",
                    }
                )
                continue

            try:
                b_img = read_2d(b_path)
                r_img = read_2d(r_path)
                g_img = read_2d(g_path)

                if not (b_img.shape == r_img.shape == g_img.shape):
                    raise ValueError(
                        "B/G/R channel shapes do not match for core "
                        f"{core}: B={b_img.shape}, G={g_img.shape}, R={r_img.shape}"
                    )

                if need_nuc or need_cyto:
                    if models is None:
                        models = require_cellpose()

                if need_nuc:
                    if nuclear_model is None:
                        nuclear_model = models.Cellpose(gpu=args.gpu, model_type="nuclei")
                    nuclear_mask = evaluate_cellpose(
                        nuclear_model,
                        b_img,
                        channels=[0, 0],
                        diameter=args.nuc_diam,
                        flow_threshold=args.nuc_flow,
                        cellprob_threshold=args.nuc_cellprob,
                    )
                    imwrite(out_nuc, nuclear_mask, compression="zlib")

                cytoplasm_mask: np.ndarray | None = None
                if need_cyto:
                    if cytoplasm_model is None:
                        cytoplasm_model = models.Cellpose(gpu=args.gpu, model_type=args.cyto_model)

                    if args.cyto_use_dapi:
                        cytoplasm_input = np.stack([r_img, b_img], axis=-1)
                        cytoplasm_channels = [1, 2]
                    else:
                        cytoplasm_input = r_img
                        cytoplasm_channels = [0, 0]

                    cytoplasm_mask = evaluate_cellpose(
                        cytoplasm_model,
                        cytoplasm_input,
                        channels=cytoplasm_channels,
                        diameter=args.cyto_diam,
                        flow_threshold=args.cyto_flow,
                        cellprob_threshold=args.cyto_cellprob,
                    )
                    imwrite(out_cyto, cytoplasm_mask, compression="zlib")

                if need_prot:
                    if cytoplasm_mask is None and os.path.exists(out_cyto):
                        cytoplasm_mask = read_2d(out_cyto)

                    tumor_region: np.ndarray | None
                    if cytoplasm_mask is not None and int(np.count_nonzero(cytoplasm_mask)) >= 50:
                        tumor_region = cytoplasm_mask > 0
                    else:
                        try:
                            r_float = img_as_float32(r_img)
                            r_threshold = filters.threshold_otsu(r_float)
                            tumor_region = r_float > r_threshold
                        except Exception:
                            tumor_region = None

                    protein_mask = protein_mask_from_image(
                        g_img,
                        tumor_region=tumor_region,
                        min_size=args.prot_min_size,
                        close_radius=args.prot_close_r,
                    )
                    imwrite(out_prot, protein_mask, compression="zlib")

                created = []
                if need_nuc:
                    created.append("nuclei")
                if need_cyto:
                    created.append("cytoplasm")
                if need_prot:
                    created.append("protein")

                output_rows.append(
                    {
                        "group": group_name,
                        "core": core,
                        "B_img": b_path,
                        "R_img": r_path,
                        "G_img": g_path,
                        "B_nuc_mask": out_nuc,
                        "R_cyto_mask": out_cyto,
                        "G_prot_mask": out_prot,
                        "status": "ok:" + ",".join(created),
                    }
                )

            except Exception as exc:
                output_rows.append(
                    {
                        "group": group_name,
                        "core": core,
                        "B_img": b_path,
                        "R_img": r_path,
                        "G_img": g_path,
                        "B_nuc_mask": out_nuc,
                        "R_cyto_mask": out_cyto,
                        "G_prot_mask": out_prot,
                        "status": f"error: {exc}",
                    }
                )

    timestamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    Path(args.outdir).mkdir(parents=True, exist_ok=True)
    manifest_path = os.path.join(args.outdir, f"mask_manifest_S_{timestamp}.csv")
    pd.DataFrame(output_rows).to_csv(manifest_path, index=False)

    params_path = os.path.join(args.outdir, f"segment_s_params_{timestamp}.json")
    with open(params_path, "w", encoding="utf-8") as handle:
        json.dump(vars(args), handle, indent=2, default=str)

    print(f"[OK] Mask manifest: {manifest_path}")
    print(f"[OK] Parameters:    {params_path}")


def mask_map(directory: str, suffix: str) -> dict[str, str]:
    """Map normalized core IDs to existing mask paths with a given suffix."""
    if not os.path.isdir(directory):
        raise FileNotFoundError(f"Expected directory: {directory}")
    paths = [
        os.path.join(directory, filename)
        for filename in os.listdir(directory)
        if filename.lower().endswith(suffix.lower())
    ]
    return {core_norm_from_fname(path): path for path in sorted(paths)}


def nuclei_per_cell_counts(nuclear_mask: np.ndarray, cell_mask: np.ndarray) -> tuple[int, int, int]:
    """Count cell labels overlapping zero, one, or more than one nucleus label."""
    cell_ids = np.unique(cell_mask)
    cell_ids = cell_ids[cell_ids > 0]

    zero = one = multiple = 0
    for cell_id in cell_ids:
        nucleus_ids = np.unique(nuclear_mask[cell_mask == cell_id])
        nucleus_ids = nucleus_ids[nucleus_ids > 0]
        count = int(nucleus_ids.size)
        if count == 0:
            zero += 1
        elif count == 1:
            one += 1
        else:
            multiple += 1
    return zero, one, multiple


def cmd_qc(args: argparse.Namespace) -> None:
    """Summarize segmentation object counts and nuclei-per-cell overlap."""
    groups = [("S_exon", args.s_exon_root), ("S_noexon", args.s_noex_root)]
    rows: list[dict[str, object]] = []

    for group_name, root in groups:
        b_dir = os.path.join(root, CHANNEL_DIRS["B"])
        r_dir = os.path.join(root, CHANNEL_DIRS["R"])

        nuc_map = mask_map(b_dir, "_nuc_masks.tif")
        cyto_map = mask_map(r_dir, "_cp_masks.tif")
        common = sorted(set(nuc_map) & set(cyto_map))
        if args.max_cores > 0:
            common = common[: args.max_cores]

        print(f"[{group_name}] cores with nuclear and cytoplasmic masks: {len(common)}")

        for core in tqdm(common, desc=f"qc {group_name}", ncols=90):
            try:
                nuclear_mask = read_2d(nuc_map[core]).astype(np.int64, copy=False)
                cell_mask = read_2d(cyto_map[core]).astype(np.int64, copy=False)
                if nuclear_mask.shape != cell_mask.shape:
                    raise ValueError(
                        f"Mask shapes do not match: nuclei={nuclear_mask.shape}, "
                        f"cytoplasm={cell_mask.shape}"
                    )

                n_cells = int(np.unique(cell_mask[cell_mask > 0]).size)
                n_nuclei = int(np.unique(nuclear_mask[nuclear_mask > 0]).size)
                zero, one, multiple = nuclei_per_cell_counts(nuclear_mask, cell_mask)

                rows.append(
                    {
                        "group": group_name,
                        "core": core,
                        "n_cells": n_cells,
                        "n_nuclei": n_nuclei,
                        "cells_0_nuc": int(zero),
                        "cells_1_nuc": int(one),
                        "cells_gt1_nuc": int(multiple),
                        "frac_cells_1_nuc": float(one / n_cells) if n_cells else np.nan,
                        "status": "ok",
                    }
                )
            except Exception as exc:
                rows.append(
                    {
                        "group": group_name,
                        "core": core,
                        "n_cells": np.nan,
                        "n_nuclei": np.nan,
                        "cells_0_nuc": np.nan,
                        "cells_1_nuc": np.nan,
                        "cells_gt1_nuc": np.nan,
                        "frac_cells_1_nuc": np.nan,
                        "status": f"error: {exc}",
                    }
                )

    timestamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    Path(args.outdir).mkdir(parents=True, exist_ok=True)
    output_csv = os.path.join(args.outdir, f"qc_S_{timestamp}.csv")
    pd.DataFrame(rows).to_csv(output_csv, index=False)

    params_path = os.path.join(args.outdir, f"qc_s_params_{timestamp}.json")
    with open(params_path, "w", encoding="utf-8") as handle:
        json.dump(vars(args), handle, indent=2, default=str)

    print(f"[OK] QC table:   {output_csv}")
    print(f"[OK] Parameters: {params_path}")


def add_common_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--s_exon_root", required=True, help="SMNDC1 Exon4 dataset root.")
    parser.add_argument("--s_noex_root", required=True, help="SMNDC1 NoExon4 dataset root.")
    parser.add_argument("--outdir", required=True, help="Directory for manifests/QC tables and parameter logs.")
    parser.add_argument(
        "--max_cores",
        type=int,
        default=0,
        help="Limit the number of cores per condition for testing (0 = all).",
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Cellpose segmentation and segmentation QC for SMNDC1 TMA sections."
    )
    subparsers = parser.add_subparsers(dest="cmd", required=True)

    segment_parser = subparsers.add_parser(
        "segment",
        aliases=["segment_s"],
        help="Segment nuclei and cytoplasm with Cellpose and create a binary protein mask.",
    )
    add_common_arguments(segment_parser)
    segment_parser.add_argument("--gpu", action="store_true", help="Use GPU acceleration in Cellpose.")
    segment_parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Recompute and replace existing masks. Without this flag, existing masks are preserved.",
    )

    segment_parser.add_argument("--nuc_diam", type=float, default=0.0, help="Nuclear diameter in pixels (0 = Cellpose automatic estimate).")
    segment_parser.add_argument("--nuc_flow", type=float, default=0.4, help="Cellpose nuclear flow threshold.")
    segment_parser.add_argument("--nuc_cellprob", type=float, default=0.0, help="Cellpose nuclear cell-probability threshold.")

    segment_parser.add_argument(
        "--cyto_model",
        default="cyto2",
        choices=["cyto", "cyto2", "cyto3"],
        help="Cellpose model used for cytoplasmic/tumor-cell segmentation.",
    )
    segment_parser.add_argument(
        "--cyto_use_dapi",
        action="store_true",
        help="Use the two-channel [panCK/cytoplasm, nuclei] input for cytoplasmic segmentation.",
    )
    segment_parser.add_argument("--cyto_diam", type=float, default=0.0, help="Cytoplasmic/cell diameter in pixels (0 = Cellpose automatic estimate).")
    segment_parser.add_argument("--cyto_flow", type=float, default=0.4, help="Cellpose cytoplasmic flow threshold.")
    segment_parser.add_argument("--cyto_cellprob", type=float, default=0.0, help="Cellpose cytoplasmic cell-probability threshold.")

    segment_parser.add_argument("--prot_min_size", type=int, default=16, help="Minimum connected-component size for the binary protein mask.")
    segment_parser.add_argument("--prot_close_r", type=int, default=1, help="Binary-closing disk radius for the protein mask.")
    segment_parser.set_defaults(func=cmd_segment)

    qc_parser = subparsers.add_parser(
        "qc",
        aliases=["qc_s"],
        help="Summarize cell counts, nuclear counts, and nuclei-per-cell overlap.",
    )
    add_common_arguments(qc_parser)
    qc_parser.set_defaults(func=cmd_qc)

    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
